def _blank_phase3_lr_middles(state):
    chars = list(state)
    chars[37] = "."
    chars[87] = "."
    return "".join(chars)


def _phase3_legal_moves():
    return tuple(move for move in moves_555 if move not in PHASE3_ILLEGAL_MOVES)


def _phase3_outer_partner_flip_mask():
    cube = RubiksCube555(solved_555, "URFDLB")
    highlow = dict(
        zip((square for square, _ in cube.reduce333_orient_edges_tuples), cube.highlow_edges_state())
    )
    mask = 0
    for index, (square, partner) in enumerate(zip(PHASE3_OUTER_WING_SQUARES_555, PHASE3_OUTER_WING_PARTNERS_555)):
        if highlow[square] != highlow[partner]:
            mask |= 1 << index
    return mask


def _phase3_outer_move_flip_masks():
    masks = []
    scramble = ("U", "L", "F2", "R'", "B", "D2", "F", "U'", "L2")
    for move in _phase3_legal_moves():
        actual = RubiksCube555(solved_555, "URFDLB")
        for step in scramble:
            actual.rotate(step)
        pattern = ["."] * len(actual.state)
        highlow_by_square = dict(
            zip(
                (square for square, _ in actual.reduce333_orient_edges_tuples),
                actual.highlow_edges_state(),
            )
        )
        for square, value in highlow_by_square.items():
            pattern[square] = value
        pattern_cube = RubiksCube555(solved_555, "URFDLB")
        pattern_cube.state = pattern
        actual.rotate(move)
        pattern_cube.rotate(move)
        expected = dict(
            zip(
                (square for square, _ in actual.reduce333_orient_edges_tuples),
                actual.highlow_edges_state(),
            )
        )
        mask = 0
        for index, (square, partner) in enumerate(
            zip(PHASE3_OUTER_WING_SQUARES_555, PHASE3_OUTER_WING_PARTNERS_555)
        ):
            if pattern_cube.state[square] != expected[square]:
                mask |= 1 << index
        masks.append(mask)
    return tuple(masks)


def _phase3_inner_move_flip_masks():
    masks = []
    for move in _phase3_legal_moves():
        flipped = set()
        if move in ("L", "L'"):
            flipped = PHASE3_INNER_L_MIDGES_555
        elif move in ("R", "R'"):
            flipped = PHASE3_INNER_R_MIDGES_555
        mask = 0
        for index, (square, partner) in enumerate(
            zip(PHASE3_INNER_MIDGE_SQUARES_555, PHASE3_INNER_MIDGE_PARTNERS_555)
        ):
            if square in flipped or partner in flipped:
                mask |= 1 << index
        masks.append(mask)
    return tuple(masks)


